import type { SeedContent } from "./load";

const lit = (v: string | null | undefined) => (v == null ? "null" : `'${v.replace(/'/g, "''")}'`);
const arr = (xs: string[]) => `array[${xs.map(lit).join(", ")}]::text[]`;

// Never downgrade: a draft in the seed doesn't undo an approval made in the admin.
const keepStatus = (table: string) =>
  `status = case when ${table}.status in ('approved', 'retired') and excluded.status = 'draft' then ${table}.status else excluded.status end`;

/** Idempotent SQL that upserts all seed content (for the SQL editor or `supabase db reset`). */
export function buildSeedSql(content: SeedContent): string {
  const out: string[] = ["-- Generated by `npm run content:sql`. Do not edit; edit /content and regenerate.", "begin;"];

  for (const q of content.questions) {
    out.push(
      `insert into public.questions (id, lang, category, difficulty, country_tags, question, options, answer_index, explanation, source_url, status) values (` +
        [lit(q.id), lit(q.lang), lit(q.category), `${lit(q.difficulty)}::public.difficulty`, arr(q.country_tags), lit(q.question), arr(q.options), q.answer_index, lit(q.explanation ?? null), lit(q.source_url ?? null), `${lit(q.status)}::public.content_status`].join(", ") +
        `) on conflict (id) do update set lang = excluded.lang, category = excluded.category, difficulty = excluded.difficulty, country_tags = excluded.country_tags, question = excluded.question, options = excluded.options, answer_index = excluded.answer_index, explanation = excluded.explanation, source_url = excluded.source_url, ${keepStatus("questions")};`,
    );
  }
  for (const w of content.charades) {
    out.push(
      `insert into public.charades_words (lang, word, category, difficulty, status) values (${lit(w.lang)}, ${lit(w.word)}, ${lit(w.category)}, ${w.difficulty}, ${lit(w.status)}::public.content_status) on conflict (lang, word) do update set category = excluded.category, difficulty = excluded.difficulty, ${keepStatus("charades_words")};`,
    );
  }
  for (const p of content.prompts) {
    out.push(
      `insert into public.prompts (id, lang, text, mood_min, status) values (${lit(p.id)}, ${lit(p.lang)}, ${lit(p.text)}, ${lit(p.mood_min)}::public.mood, ${lit(p.status)}::public.content_status) on conflict (id) do update set lang = excluded.lang, text = excluded.text, mood_min = excluded.mood_min, ${keepStatus("prompts")};`,
    );
  }
  for (const t of content.traits) {
    out.push(
      `insert into public.traits (id, lang, text, mood_min, banned, status) values (${lit(t.id)}, ${lit(t.lang)}, ${lit(t.text)}, ${lit(t.mood_min)}::public.mood, ${t.banned}, ${lit(t.status)}::public.content_status) on conflict (id) do update set lang = excluded.lang, text = excluded.text, mood_min = excluded.mood_min, banned = excluded.banned, ${keepStatus("traits")};`,
    );
  }
  out.push("commit;", "");
  return out.join("\n");
}
